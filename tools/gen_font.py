# Generates src/ui/font_data.h: an 8x12 1-bit bitmap font (ASCII 32..126) rasterized once from DejaVu Sans Mono Bold.
# The output is plain C data, so the game ships no font assets.
from PIL import Image, ImageDraw, ImageFont
import glob
path = (glob.glob('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf') + glob.glob('/usr/share/fonts/**/DejaVuSansMono-Bold.ttf', recursive=True))[0]
font = ImageFont.truetype(path, 11)
W, H = 8, 12
rows = []
for c in range(32, 127):
    im = Image.new('L', (W, H), 0); d = ImageDraw.Draw(im)
    d.text((0, -1), chr(c), fill=255, font=font)
    g = []
    for y in range(H):
        b = 0
        for x in range(W):
            if im.getpixel((x, y)) > 110: b |= 1 << (7 - x)
        g.append(b)
    rows.append(g)
out = ['// Generated by tools/gen_font.py (8x12 bitmap, ASCII 32..126). Derived from DejaVu Sans Mono (free license).',
       '#pragma once', '#include <cstdint>', 'namespace tz { constexpr int FONT_W = 8, FONT_H = 12;', 'static const uint8_t FONT_DATA[95][12] = {']
for i, g in enumerate(rows):
    out.append('  {' + ','.join('0x%02x' % v for v in g) + '}, // ' + repr(chr(32 + i)))
out.append('}; }')
open('src/ui/font_data.h', 'w').write('\n'.join(out) + '\n')
# preview
for ch in 'Tz7':
    g = rows[ord(ch) - 32]
    print('\n'.join(''.join('#' if v & (1 << (7 - x)) else '.' for x in range(8)) for v in g)); print()
