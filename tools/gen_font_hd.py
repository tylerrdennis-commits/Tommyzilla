# Vault: generates src/ui/font_hd.h - a cleaner 16x24 body-text font (ASCII 32..126) from DejaVu Sans Bold, drawn
# centred in the same monospace cell as the chunky 8x12 font (so layouts don't move) at half the pixel size.
# Two coverage masks per row: solid (>=50%) and edge (20-50%, drawn at half alpha) for smoother outlines.
from PIL import Image, ImageDraw, ImageFont
import glob
path = (glob.glob('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf') + glob.glob('/usr/share/fonts/**/DejaVuSans-Bold.ttf', recursive=True))[0]
font = ImageFont.truetype(path, 19)
W, H = 16, 24
solid, edge = [], []
for c in range(32, 127):
    im = Image.new('L', (W * 2, H), 0); d = ImageDraw.Draw(im)
    bb = d.textbbox((0, 0), chr(c), font=font); gw = bb[2] - bb[0]
    sc = min(1.0, (W - 1) / gw) if gw > 0 else 1.0
    if sc < 1.0:  # squeeze wide glyphs (M, W, @) into the cell
        big = Image.new('L', (W * 3, H), 0); ImageDraw.Draw(big).text((-bb[0], -2), chr(c), fill=255, font=font)
        big = big.crop((0, 0, max(1, gw), H)).resize((max(1, int(gw * sc)), H), Image.LANCZOS)
        im = Image.new('L', (W, H), 0); im.paste(big, ((W - big.size[0]) // 2, 0))
    else:
        im = Image.new('L', (W, H), 0); ImageDraw.Draw(im).text(((W - gw) // 2 - bb[0], -2), chr(c), fill=255, font=font)
    s, e = [], []
    for y in range(H):
        a = b = 0
        for x in range(W):
            v = im.getpixel((x, y))
            if v >= 128: a |= 1 << (15 - x)
            elif v >= 50: b |= 1 << (15 - x)
        s.append(a); e.append(b)
    solid.append(s); edge.append(e)
def arr(name, g): return 'static const uint16_t %s[95][24] = {\n' % name + ',\n'.join('  {' + ','.join('0x%04x' % v for v in r) + '}' for r in g) + '};'
out = ['// Generated by tools/gen_font_hd.py (16x24 body font, ASCII 32..126, solid + edge masks). Derived from DejaVu Sans Bold (free license).',
       '#pragma once', '#include <cstdint>', 'namespace tz { constexpr int FONTHD_W = 16, FONTHD_H = 24;', arr('FONTHD_SOLID', solid), arr('FONTHD_EDGE', edge), '}  // namespace tz', '']
open('src/ui/font_hd.h', 'w').write('\n'.join(out))
